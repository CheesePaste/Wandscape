package org.magiccolony.core.types;

/**
 * Behaviour tags that define what a wand can do.
 * Used as keys in WandCarrier capability maps and task requirements.
 */
public enum BehaviourTag {
    BUILDING,
    FARMING,
    MINING,
    LOGGING,
    CRAFTING,
    GATHERING,
    RITUAL,
    ENTITY_INTERACTION
}
